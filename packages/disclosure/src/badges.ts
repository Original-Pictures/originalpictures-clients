// The EU AI badge set: four visible labels in brand light, brand dark and a
// neutral variant. These are Original Pictures designs, not an official EU
// mark; the Commission has published no mandatory icon. assets/badges holds
// the same SVGs as files (scripts/generate.mjs writes them from badgeSvg).

import { BRAND, BRASS_DEEP, FONT_STACK } from "./tokens.ts";
import { BADGE_IDS, BADGE_VARIANTS, type BadgeId, type BadgeVariant } from "./policy-types.ts";

export { BADGE_IDS, BADGE_VARIANTS, type BadgeId, type BadgeVariant };

export const BADGE_LABELS: Readonly<Record<BadgeId, string>> = {
  "ai-generated": "AI-generated",
  "ai-manipulated": "AI-manipulated",
  "ai-interaction": "AI interaction",
  "ai-assisted": "AI-assisted",
};

export const BADGE_DESCRIPTIONS: Readonly<Record<BadgeId, string>> = {
  "ai-generated": "This content was generated by AI.",
  "ai-manipulated": "This real-looking content was generated or manipulated by AI.",
  "ai-interaction": "You are interacting with an AI system, not a person.",
  "ai-assisted": "A person made this content with help from AI tools.",
};

export const BADGE_NOTICE = "Original Pictures badge design; not an official EU mark.";

interface Palette {
  background: string;
  border: string;
  text: string;
  glyph: string;
}

// Each pair reads at WCAG AA or better (tests/badges.test.ts).
const PALETTES: Readonly<Record<BadgeVariant, Palette>> = {
  "brand-light": {
    background: BRAND.paper,
    border: BRAND.deepSea,
    text: BRAND.deepSea,
    glyph: BRASS_DEEP,
  },
  "brand-dark": {
    background: BRAND.deepSea,
    border: BRAND.brass,
    text: BRAND.paleBlue,
    glyph: BRAND.brass,
  },
  neutral: { background: "#FFFFFF", border: "#1A1A1A", text: "#1A1A1A", glyph: "#1A1A1A" },
};

export function badgePalette(variant: BadgeVariant): Palette {
  return PALETTES[variant];
}

// 16 x 16 glyphs drawn at (8, 6).
const GLYPHS: Readonly<Record<BadgeId, (colour: string) => string>> = {
  "ai-generated": (c) =>
    `<path fill="${c}" d="M8 1.5 9.7 6.3 14.5 8 9.7 9.7 8 14.5 6.3 9.7 1.5 8 6.3 6.3Z"/>`,
  "ai-manipulated": (c) =>
    `<rect x="2" y="2" width="12" height="12" rx="1.5" fill="none" stroke="${c}" stroke-width="1.5"/>` +
    `<path fill="${c}" d="M2.75 13.25 13.25 2.75v10.5Z"/>`,
  "ai-interaction": (c) =>
    `<path fill="none" stroke="${c}" stroke-width="1.5" stroke-linejoin="round" d="M2.5 3h11a1 1 0 0 1 1 1v6.5a1 1 0 0 1-1 1H8L4.5 14v-2.5h-2a1 1 0 0 1-1-1V4a1 1 0 0 1 1-1Z"/>` +
    `<circle cx="5.5" cy="7.25" r="1" fill="${c}"/><circle cx="8" cy="7.25" r="1" fill="${c}"/><circle cx="10.5" cy="7.25" r="1" fill="${c}"/>`,
  "ai-assisted": (c) =>
    `<path fill="none" stroke="${c}" stroke-width="1.5" stroke-linejoin="round" d="M2.5 13.5 3.4 10 10.4 3l2.6 2.6-7 7Z"/>` +
    `<path fill="${c}" d="M13 9.5l.7 1.5 1.5.7-1.5.7-.7 1.5-.7-1.5-1.5-.7 1.5-.7Z"/>`,
};

// Average advance of IBM Plex Sans Medium at 13 px; textLength pins the
// rendered width whatever font the viewer falls back to.
const CHAR_ADVANCE = 7.35;

function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

export interface BadgeSvgOptions {
  /** Visible text; defaults to the badge label. Keep it short. */
  label?: string;
  /** Rendered height in CSS pixels (default 28, the drawing's own size). */
  height?: number;
  /** An id prefix for the <title>, unique per document when inlined. */
  idPrefix?: string;
}

/** The badge's natural size in its own units. */
export function badgeSize(label: string): { width: number; height: number } {
  return { width: Math.round(30 + label.length * CHAR_ADVANCE + 10), height: 28 };
}

/** One badge as a standalone SVG document string. */
export function badgeSvg(
  id: BadgeId,
  variant: BadgeVariant,
  options: BadgeSvgOptions = {},
): string {
  if (!(BADGE_IDS as readonly string[]).includes(id)) throw new RangeError(`unknown badge ${id}`);
  if (!(BADGE_VARIANTS as readonly string[]).includes(variant)) {
    throw new RangeError(`unknown badge variant ${variant}`);
  }
  const label = options.label ?? BADGE_LABELS[id];
  const palette = PALETTES[variant];
  const { width, height } = badgeSize(label);
  const scale = (options.height ?? height) / height;
  const titleId = `${options.idPrefix ?? "op-badge"}-${id}-${variant}`;
  const textWidth = Math.round(label.length * CHAR_ADVANCE);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${round(width * scale)}" height="${round(height * scale)}" ` +
    `viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="${titleId}">` +
    `<title id="${titleId}">${escapeXml(label)}</title>` +
    `<desc>${escapeXml(`${BADGE_DESCRIPTIONS[id]} ${BADGE_NOTICE}`)}</desc>` +
    `<rect x="0.5" y="0.5" width="${width - 1}" height="${height - 1}" rx="4" fill="${palette.background}" stroke="${palette.border}"/>` +
    `<g transform="translate(8 6)">${GLYPHS[id](palette.glyph)}</g>` +
    `<text x="30" y="18.5" fill="${palette.text}" font-family="${escapeXml(FONT_STACK)}" font-size="13" font-weight="500" ` +
    `textLength="${textWidth}" lengthAdjust="spacingAndGlyphs">${escapeXml(label)}</text>` +
    `</svg>`
  );
}

/** A data: URL for <img src>, CSS backgrounds or canvas drawing. */
export function badgeDataUrl(
  id: BadgeId,
  variant: BadgeVariant,
  options: BadgeSvgOptions = {},
): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(badgeSvg(id, variant, options))}`;
}

/** The file name of a badge in assets/badges (and dist/badges). */
export function badgeFileName(id: BadgeId, variant: BadgeVariant): string {
  return `${id}-${variant}.svg`;
}

function round(value: number): number {
  return Math.round(value * 100) / 100;
}
